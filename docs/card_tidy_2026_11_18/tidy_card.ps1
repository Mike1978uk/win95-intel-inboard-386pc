function Invoke-Ctl {
  param([string[]]$CtlArgs)
  $out = & $Ctl @CtlArgs -Host $Agent -ConnectTimeoutSeconds 90 -Json
  if ($LASTEXITCODE -ne 0) { throw "v9xctl failed ($LASTEXITCODE): $($CtlArgs -join ' ')" }
  $o = $out | ConvertFrom-Json
  if (-not $o.Success) { throw "agent refused: $($CtlArgs -join ' '): $out" }
  return $o
}

"{0} paths listed" -f $Paths.Count
if ($WhatIf) {
  foreach ($p in $Paths) { "WhatIf: get $p -> $ArchiveRoot\$($p.Substring(3)); then DEL" }
  return
}

# Phase 1: archive and verify
foreach ($p in $Paths) {
  $dest = Join-Path $ArchiveRoot $p.Substring(3)
  New-Item -ItemType Directory -Force (Split-Path $dest) | Out-Null
  $st = Invoke-Ctl @('stat', '-Path', $p)
  if (-not $st.Exists) { throw "missing on card: $p" }
  Invoke-Ctl @('get', '-Source', $p, '-Destination', $dest) | Out-Null
  $len = (Get-Item -LiteralPath $dest).Length
  if ($len -ne $st.Size) { throw "size mismatch for ${p}: card $($st.Size), archive $len" }
  "archived $p ($len)"
}

# Phase 2: one DEL batch, one shell call
$bat = Join-Path $ArchiveRoot 'TIDY.BAT'
$lines = @('@ECHO OFF')
foreach ($p in $Paths) { $lines += "ATTRIB -R -S -H `"$p`""; $lines += "DEL `"$p`"" }
Set-Content -LiteralPath $bat -Value $lines -Encoding ascii
Invoke-Ctl @('mkdir', '-Path', 'C:\V9XREMOTE\JOBS\tidy') | Out-Null
Invoke-Ctl @('put', '-Source', $bat, '-Destination', 'C:\V9XREMOTE\JOBS\tidy\TIDY.BAT') | Out-Null
Invoke-Ctl @('shell', '-Command', 'C:\V9XREMOTE\JOBS\tidy\TIDY.BAT', '-TimeoutSeconds', '900') | Out-Null

# Phase 3: verify
